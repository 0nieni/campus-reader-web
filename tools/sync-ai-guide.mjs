import { readFileSync, writeFileSync } from 'node:fs';
const input = new URL('../docs/ai-reading-guide.md', import.meta.url);
const target = new URL('../apps/cloud/src/chat-guide.ts', import.meta.url);
const md = readFileSync(input, 'utf8').replace(/\r\n/g, '\n');
const content = md.split('## 模型任务指令\n')[1]?.split('## 软件接入约定')[0]?.trim();
if (!content) throw new Error('Missing AI guide instruction boundaries');
const generated = '// Generated by tools/sync-ai-guide.mjs from docs/ai-reading-guide.md.\nexport const CHAT_GUIDE_VERSION = "conversation-v2.2";\nexport const CHAT_READING_GUIDE = ' + JSON.stringify(content) + ';\n';
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== generated) throw new Error('Chat guide differs from Markdown. Run node tools/sync-ai-guide.mjs');
  console.log('Chat guide matches Markdown');
} else writeFileSync(target, generated);
